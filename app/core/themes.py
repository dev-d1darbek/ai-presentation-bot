THEMES_LIST: List[ThemeConfig] = list(THEMES_REGISTRY.values())

def get_theme_heading_color(theme: ThemeConfig) -> str:
    dark_blacks = {'000000', '050505', '09090B', '0A0A0A', '0C0A09', '030712', '0B1120', '1A1412', '1E1035'}
    if theme.isDark:
        if theme.primaryColor and theme.primaryColor not in dark_blacks:
            return theme.primaryColor
        return theme.textColor or 'FFFFFF'
    return theme.primaryColor or '111827'

def detect_best_theme_for_topic(topic: str) -> ThemeConfig:
    t = topic.lower()

    if any(w in t for w in ['интеллект', 'ai', 'ит', 'робот', 'кибер', 'бағдарлама', 'код', 'it']):
        return THEMES_REGISTRY['futuristic_tech']
    if any(w in t for w in ['тарих', 'батыр', 'хан', 'соғыс', 'алаш', 'ежелгі', 'дәуір', 'қазақ хандығы']):
        return THEMES_REGISTRY['cinematic_history']
    if any(w in t for w in ['абай', 'шәкәрім', 'әуезов', 'ақын', 'әдебиет', 'жазушы', 'жыр', 'роман']):
        return THEMES_REGISTRY['editorial_magazine']
    if any(w in t for w in ['бизнес', 'жоспар', 'қаржы', 'инвест', 'компания', 'кәсіпкер', 'маркетинг']):
        return THEMES_REGISTRY['corporate_premium']
    if any(w in t for w in ['стартап', 'питч', 'қосымша', 'mobile', 'платформа', 'app']):
        return THEMES_REGISTRY['startup_pitch_deck']
    if any(w in t for w in ['биология', 'медицина', 'денсаулық', 'дәрі', 'анатомия', 'дәрігер', 'ауру']):
        return THEMES_REGISTRY['medical_professional']
    if any(w in t for w in ['табиғат', 'экология', 'жасыл', 'климат', 'жануарлар', 'өсімдік', 'жер']):
        return THEMES_REGISTRY['nature_organic']
    if any(w in t for w in ['ғылым', 'химия', 'физика', 'зерттеу', 'ғарыш', 'астрономия', 'математика']):
        return THEMES_REGISTRY['scientific_research']
    if any(w in t for w in ['гаджет', 'apple', 'смартфон', 'өнім', 'дизайн', 'презентация']):
        return THEMES_REGISTRY['apple_keynote']
    if any(w in t for w in ['мәлімет', 'аналитика', 'статистика', 'диаграмма', 'деректер', 'big data']):
        return THEMES_REGISTRY['data_visualization']

    return THEMES_REGISTRY['swiss_minimalism']

def get_selected_theme_label(design_id: str, topic: Optional[str] = None) -> str:
    if design_id == 'auto' or design_id not in THEMES_REGISTRY:
        if topic:
            auto_theme = detect_best_theme_for_topic(topic)
            return f"Автоматты ({auto_theme.nameKz})"
        return "Автоматты (AI таңдайды)"
    return THEMES_REGISTRY[design_id].nameKz
